use std::process::Command;

fn main() {
    // For `cargo install` users: attempt a best-effort npm install so the
    // dashboard can be built out of the box. Missing node/npm or a failed
    // install is skipped. A failed `npm run build` is not: that would leave
    // `web/dist` at the previous bundle while this binary's stamp moves on.
    build_web_dashboard();
    ensure_embedded_web_dist_when_enabled();
}

fn build_web_dashboard() {
    let manifest_dir = std::env::var("CARGO_MANIFEST_DIR")
        .expect("CARGO_MANIFEST_DIR is always set by cargo for build scripts");
    let web_dir = std::path::Path::new(&manifest_dir)
        .parent()
        .and_then(|p| p.parent())
        .map(|root| root.join("web"));

    let Some(web_dir) = web_dir else { return };
    if !web_dir.join("package.json").exists() {
        return;
    }

    // Emit rerun-if-changed before any early return so cargo registers
    // the dependency. Without it, source edits don't re-invoke the
    // script and stale dist/ stays served against changed web/src.
    println!(
        "cargo:rerun-if-changed={}",
        web_dir.join("package.json").display()
    );
    println!("cargo:rerun-if-changed={}", web_dir.join("src").display());

    // The TypeScript client is generated by `cargo web gen-api`. A clean source
    // checkout intentionally lacks it, so a direct npm build would only print a
    // noisy TS2307 before the supported `cargo web build` path gets a chance to
    // regenerate it.
    if !web_dir.join("src/lib/api-generated.ts").exists() {
        return;
    }

    let npm = if cfg!(target_os = "windows") {
        "npm.cmd"
    } else {
        "npm"
    };

    let ok = Command::new(npm)
        .args(["ci", "--ignore-scripts"])
        .current_dir(&web_dir)
        .status()
        .map(|s| s.success())
        .unwrap_or(false);

    if !ok {
        // npm not available or install failed — skip silently
        return;
    }

    run_dashboard_build(npm, &web_dir);
}

/// `npm ci` already succeeded, so a failed dashboard build must fail this
/// script. Ignoring the status keeps the previous `web/dist` and lets cargo
/// embed that stale bundle under the new binary.
fn run_dashboard_build(npm: &str, web_dir: &std::path::Path) {
    let status = Command::new(npm)
        .args(["run", "build"])
        .current_dir(web_dir)
        .status()
        .unwrap_or_else(|err| {
            panic!(
                "failed to spawn `npm run build` in {}: {err}",
                web_dir.display()
            )
        });
    if !status.success() {
        panic!(
            "`npm run build` failed in {} ({status}); refusing to keep the previous web/dist",
            web_dir.display()
        );
    }
}

fn ensure_embedded_web_dist_when_enabled() {
    if std::env::var_os("CARGO_FEATURE_EMBEDDED_WEB").is_none() {
        return;
    }

    // See build_web_dashboard for why this reads the var at runtime.
    let manifest_dir = std::env::var("CARGO_MANIFEST_DIR")
        .expect("CARGO_MANIFEST_DIR is always set by cargo for build scripts");
    let web_dist = std::path::Path::new(&manifest_dir)
        .parent()
        .and_then(|p| p.parent())
        .map(|root| root.join("web/dist"))
        .unwrap_or_default();

    println!("cargo:rerun-if-changed={}", web_dist.display());

    assert!(
        web_dist.join("index.html").exists(),
        "feature `embedded-web` requires `web/dist/index.html`; run: cargo web build"
    );
}
